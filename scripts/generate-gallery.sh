#!/usr/bin/env bash
# =============================================================================
# generate-gallery.sh - build evidence/GALLERY.md from YOUR real screenshots
# Purpose : Produce a markdown page that displays every image found in
#           evidence/screenshots/ (png/jpg/jpeg), sorted by filename.
# Safety  : Only writes evidence/GALLERY.md inside this repository.
# Run as  : normal user, from anywhere:  bash scripts/generate-gallery.sh
# =============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SHOTS="$ROOT/evidence/screenshots"
OUT="$ROOT/evidence/GALLERY.md"

shopt -s nullglob nocaseglob
files=("$SHOTS"/*.png "$SHOTS"/*.jpg "$SHOTS"/*.jpeg)

if [ ${#files[@]} -eq 0 ]; then
  echo "No screenshots found in $SHOTS - capture some first (see evidence/README.md)." >&2
  exit 1
fi

{
  echo "# Screenshot Gallery"
  echo
  echo "Generated by \`scripts/generate-gallery.sh\` from the files in \`evidence/screenshots/\`."
  echo
  for f in "${files[@]}"; do
    name="$(basename "$f")"
    url="${name// /%20}"
    echo "### $name"
    echo
    echo "![${name%.*}](screenshots/$url)"
    echo
  done
} > "$OUT"

echo "Wrote $OUT with ${#files[@]} screenshot(s)."
